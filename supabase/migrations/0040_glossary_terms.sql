-- The Leap — multilingual phase 4: the translation glossary.
--
-- Approved renderings of product and theological terms per language, fed
-- to the AI translator with every request and maintained by admins (the
-- people reviewing translations) from /admin/translations/glossary.
-- Seeded from the glossaries written with the interface translations
-- (.scratch/multilingual/glossary/<locale>.md), plus Swahili terms matching
-- the interface's existing choices (Swahili Union Version tradition).
--
-- Additive only.

create table public.glossary_terms (
  id uuid primary key default gen_random_uuid(),
  locale text not null check (public.is_translation_locale(locale)),
  source_term text not null check (length(trim(source_term)) > 0),
  approved_term text not null check (length(trim(approved_term)) > 0),
  notes text,
  kind text not null default 'theology' check (kind in ('theology', 'product')),
  updated_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

create unique index glossary_terms_unique_term
  on public.glossary_terms (locale, lower(source_term));

alter table public.glossary_terms enable row level security;
-- Admin-only, read and write: readers never need it.
create policy "admin manages glossary" on public.glossary_terms
  for all using (public.is_admin()) with check (public.is_admin());

